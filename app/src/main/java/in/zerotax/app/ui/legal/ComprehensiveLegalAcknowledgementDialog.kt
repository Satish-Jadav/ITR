/**
 * Comprehensive Statutory Legal Acknowledgement & Regulatory Protection Modal.
 *
 * Enforces mandatory statutory compliance under:
 * 1. Income-tax Act, 1961 (Section 140 Verification & Section 277 False Statement Warning)
 * 2. Section 270A Under-reporting & Misreporting Penalty Protections
 * 3. Technology Intermediary & Non-CA Software Utility Disclaimers
 * 4. DPDP Act, 2023 Itemized Personal Data Processing Consent (Sections 5 & 6)
 * 5. Cloud Crash Resilience & Session Retention Agreement (Zero Data Loss Protection)
 */
@Composable
fun ComprehensiveLegalAcknowledgementDialog(
    pan: String,
    onDismiss: () -> Unit,
    onAcknowledgeAndAccept: (consentSha256: String, timestampIso: String) -> Unit,
    modifier: Modifier = Modifier
) {
    var isSec140Accepted by remember { mutableStateOf(false) }
    var isPlatformDisclaimerAccepted by remember { mutableStateOf(false) }
    var isDpdpAccepted by remember { mutableStateOf(false) }
    var isCloudRetentionAccepted by remember { mutableStateOf(false) }

    val allAccepted = isSec140Accepted && isPlatformDisclaimerAccepted && isDpdpAccepted && isCloudRetentionAccepted
    val scrollState = rememberScrollState()

    val statutoryLegalText = """
        MASTER STATUTORY ACKNOWLEDGEMENT & REGULATORY COMPLIANCE AGREEMENT
        Permanent Account Number: $pan | Assessment Year: 2026-27

        1. STATUTORY RETURN VERIFICATION UNDER SECTION 140 & PENAL CONSEQUENCES UNDER SECTION 277:
        The taxpayer solemnly declares that all income, salary components, Chapter VI-A deductions, bank accounts, and financial transactions declared in this return are true, correct, and complete to the best of their knowledge and belief. The taxpayer explicitly understands that making a false statement or declaration in verification is punishable under Section 277 of the Income-tax Act, 1961 with rigorous imprisonment (ranging from 3 months up to 7 years) and fine. Furthermore, under-reporting or misreporting of income attracts statutory penalties equal to 50% to 200% of the tax payable under Section 270A.

        2. TECHNOLOGY SOFTWARE UTILITY & NON-ADVISORY PLATFORM DISCLAIMER:
        ZeroTax is an automated, client-side assistive software utility. ZeroTax is NOT a registered Chartered Accountant firm under the Chartered Accountants Act, 1949, nor an advocate practice under the Advocates Act, 1961, nor a SEBI Registered Investment Adviser. All calculations, regime showdowns, and deduction advisories are generated by deterministic algorithmic rule engines and do not constitute formal legal opinion or guarantee of immunity from scrutiny assessment under Section 143(2) or Section 147. The taxpayer acts solely as a self-filer and bears sole statutory responsibility for all data transmitted to the Income Tax Department.

        3. DIGITAL PERSONAL DATA PROTECTION (DPDP) ACT, 2023 CONSENT (SECTIONS 5 & 6):
        The taxpayer grants express, informed, and itemized consent to process their PAN, Form 16, AIS/TIS, and bank details exclusively for preparing and filing their Income Tax Return. The platform maintains zero third-party marketing sharing, zero commercial data brokering, and guarantees the right to immediate cryptographic erasure ("Shred Local Tax Vault") under Section 12(3) of the DPDP Act, 2023.

        4. CLOUD CRASH RESILIENCE & STATE RETENTION AGREEMENT (ZERO DATA LOSS SUPPORT):
        To safeguard the taxpayer against unexpected app crashes, low-memory operating system terminations, device freezes, or battery depletion during return preparation, the taxpayer expressly authorizes ZeroTax to securely synchronize an encrypted session backup snapshot of their in-progress tax return with the authenticated cloud resilience endpoint (/api/v1/tax/backup-sync). This cloud backup is end-to-end encrypted with zero-knowledge keys, used strictly to restore the taxpayer's own session upon app restart, never accessed by human agents, and permanently expunged upon vault shredding.

        5. LIMITATION OF LIABILITY & HOLD HARMLESS INDEMNIFICATION:
        To the maximum extent permitted by Indian Law, the taxpayer agrees to hold harmless and indemnify ZeroTax, its developers, directors, and affiliates against any statutory interest (Sections 234A, 234B, 234C), late fees (Section 234F), portal gateway downtime on eportal.incometax.gov.in, or verification delays arising from taxpayer-entered figures. The platform's total cumulative liability is capped at ₹1,000 or the software subscription fee paid.
    """.trimIndent()

    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Surface(
            modifier = modifier
                .fillMaxWidth(0.95f)
                .fillMaxHeight(0.92f)
                .clip(RoundedCornerShape(8.dp)),
            color = MaterialTheme.colorScheme.surface,
            tonalElevation = 6.dp,
            border = CardDefaults.outlinedCardBorder().copy(
                width = 1.dp,
                brush = androidx.compose.ui.graphics.SolidColor(EnterpriseTeal600.copy(alpha = 0.5f))
            )
        ) {
            Column(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(16.dp)
            ) {
                // Header
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Column {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Text("⚖️", fontSize = 18.sp)
                            Spacer(Modifier.width(8.dp))
                            Text(
                                text = "Statutory Legal Acknowledgement",
                                style = MaterialTheme.typography.titleMedium.copy(fontWeight = FontWeight.Bold)
                            )
                        }
                        Text(
                            text = "Income-tax Act §140 • DPDP Act §6 • Cloud Crash-Resilience",
                            style = MaterialTheme.typography.labelSmall,
                            color = Slate500
                        )
                    }
                    StatutoryBadge(text = "PAN $pan", tone = BadgeTone.STATUTORY)
                }

                Spacer(Modifier.height(12.dp))

                // Scrollable Legal Terms Body
                Box(
                    modifier = Modifier
                        .weight(1f)
                        .fillMaxWidth()
                        .clip(RoundedCornerShape(4.dp))
                        .background(Slate50)
                        .border(0.75.dp, Slate200, RoundedCornerShape(4.dp))
                        .padding(12.dp)
                        .verticalScroll(scrollState)
                ) {
                    Column {
                        Text(
                            text = "Please read the following statutory declarations and regulatory terms before proceeding:",
                            style = MaterialTheme.typography.labelSmall.copy(fontWeight = FontWeight.Bold, color = Slate700)
                        )
                        Spacer(Modifier.height(8.dp))
                        Text(
                            text = statutoryLegalText,
                            style = TextStyle(
                                fontFamily = FontFamily.Monospace,
                                fontSize = 11.sp,
                                lineHeight = 16.sp,
                                color = Slate800
                            )
                        )
                    }
                }

                Spacer(Modifier.height(12.dp))

                // 4 Mandatory Statutory Gates / Checkboxes
                Text(
                    text = "Mandatory Declarations (Check all to proceed):",
                    style = MaterialTheme.typography.labelSmall.copy(fontWeight = FontWeight.Bold)
                )
                Spacer(Modifier.height(6.dp))

                Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
                    // Checkbox 1: Section 140
                    AcknowledgementCheckboxRow(
                        checked = isSec140Accepted,
                        onCheckedChange = { isSec140Accepted = it },
                        title = "1. Section 140 Return Verification & Section 277 Penalty Awareness",
                        subtitle = "I solemnly declare that all income and deductions are authentic and complete. I understand false statements are punishable with imprisonment."
                    )

                    // Checkbox 2: Non-CA Utility
                    AcknowledgementCheckboxRow(
                        checked = isPlatformDisclaimerAccepted,
                        onCheckedChange = { isPlatformDisclaimerAccepted = it },
                        title = "2. Software Utility Platform & Self-Filer Responsibility",
                        subtitle = "I acknowledge ZeroTax is an automated software tool (not a CA firm), and I am solely responsible for my statutory tax return."
                    )

                    // Checkbox 3: DPDP Act 2023
                    AcknowledgementCheckboxRow(
                        checked = isDpdpAccepted,
                        onCheckedChange = { isDpdpAccepted = it },
                        title = "3. DPDP Act, 2023 Section 6 Data Processing Consent",
                        subtitle = "I consent to the on-device processing of my tax records solely for filing purposes, with right to shred local vault anytime."
                    )

                    // Checkbox 4: Cloud Crash Resilience (User's specific requirement)
                    AcknowledgementCheckboxRow(
                        checked = isCloudRetentionAccepted,
                        onCheckedChange = { isCloudRetentionAccepted = it },
                        title = "4. Cloud Crash Resilience & Session State Retention Consent",
                        subtitle = "I consent to encrypted cloud backup synchronization so that if the app crashes or device shuts down, my return state is safely retained."
                    )
                }

                Spacer(Modifier.height(14.dp))

                // Action Buttons
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    OutlinedButton(
                        onClick = onDismiss,
                        shape = RoundedCornerShape(4.dp),
                        modifier = Modifier.weight(1f).height(44.dp)
                    ) {
                        Text("Cancel", style = MaterialTheme.typography.labelMedium)
                    }

                    Button(
                        onClick = {
                            val computedHash = CanonicalWarningHasher.computeSha256(statutoryLegalText)
                            val timestamp = Instant.now().toString()
                            onAcknowledgeAndAccept(computedHash, timestamp)
                        },
                        enabled = allAccepted,
                        shape = RoundedCornerShape(4.dp),
                        colors = ButtonDefaults.buttonColors(
                            containerColor = if (allAccepted) EnterpriseTeal600 else Slate300
                        ),
                        modifier = Modifier.weight(2f).height(44.dp)
                    ) {
                        Text(
                            text = if (allAccepted) "I Solemnly Acknowledge & Accept Terms →" else "Check All 4 Clauses to Proceed",
                            style = MaterialTheme.typography.labelMedium.copy(fontWeight = FontWeight.Bold)
                        )
                    }
                }
            }
        }
    }
}

@Composable
private fun AcknowledgementCheckboxRow(
    checked: Boolean,
    onCheckedChange: (Boolean) -> Unit,
    title: String,
    subtitle: String,
    modifier: Modifier = Modifier
) {
    Row(
        modifier = modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(4.dp))
            .background(if (checked) EnterpriseTeal50 else Slate100)
            .border(
                width = 0.5.dp,
                color = if (checked) EnterpriseTeal600.copy(alpha = 0.5f) else Slate300,
                shape = RoundedCornerShape(4.dp)
            )
            .clickable { onCheckedChange(!checked) }
            .padding(horizontal = 8.dp, vertical = 6.dp),
        verticalAlignment = Alignment.Top
    ) {
        Checkbox(
            checked = checked,
            onCheckedChange = onCheckedChange,
            colors = CheckboxDefaults.colors(checkedColor = EnterpriseTeal600),
            modifier = Modifier.size(24.dp).padding(top = 2.dp)
        )
        Spacer(Modifier.width(8.dp))
        Column {
            Text(
                text = title,
                style = MaterialTheme.typography.labelSmall.copy(
                    fontWeight = FontWeight.Bold,
                    color = if (checked) EnterpriseTeal900 else Slate900
                )
            )
            Text(
                text = subtitle,
                style = TextStyle(fontSize = 10.sp, lineHeight = 13.sp, color = Slate600)
            )
        }
    }
}
